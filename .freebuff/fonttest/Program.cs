using System.IO;
using SkiaSharp;
var typeface = SKTypeface.FromFile(args[0])!;
using var bmp = new SKBitmap(900, 320);
using var canvas = new SKCanvas(bmp);
canvas.Clear(SKColors.White);
using var paint = new SKPaint { Color = SKColors.Black, IsAntialias = true, Typeface = typeface };
paint.TextSize = 48;
canvas.DrawText("Spectrum", 20, 70, paint);
paint.TextSize = 28;
canvas.DrawText("Spectrum", 20, 130, paint);
paint.TextSize = 48;
canvas.DrawText("COLOR REFERENCE", 20, 200, paint);
paint.TextSize = 24;
canvas.DrawText("Studio  Analyze  Export", 20, 260, paint);
canvas.Flush();
using var img = SKImage.FromBitmap(bmp);
using var data = img.Encode(SKEncodedImageFormat.Png, 100);
File.WriteAllBytes(args[1], data.ToArray());
System.Console.WriteLine("wrote " + args[1]);
